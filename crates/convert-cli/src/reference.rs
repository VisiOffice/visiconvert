//! Markdown reference pages for the docs site, generated from the clap
//! definitions and the MCP tool table so they cannot drift from the code.

use clap::{Arg, ArgAction, Command};
use serde_json::Value;

pub fn cli(root: &Command) -> String {
    let mut out = String::from(
        "---\ntitle: Command reference\ndescription: Every visiconvert command and option.\n---\n\n\
         {/* Generated by `visiconvert reference cli`. Do not edit by hand. */}\n\n\
         Every command accepts `--json`, which prints JSON instead of tables. \
         Errors exit with status 1; with `--json` they print `{\"error\": \"…\"}`.\n",
    );
    for sub in visible(root) {
        command(&mut out, sub, root.get_name());
    }
    out
}

fn visible(cmd: &Command) -> impl Iterator<Item = &Command> {
    cmd.get_subcommands()
        .filter(|c| !c.is_hide_set() && c.get_name() != "help")
}

fn command(out: &mut String, cmd: &Command, parent: &str) {
    let path = format!("{parent} {}", cmd.get_name());
    if cmd.has_subcommands() {
        for sub in visible(cmd) {
            command(out, sub, &path);
        }
        return;
    }
    out.push_str(&format!("\n## `{path}`\n\n"));
    if let Some(about) = cmd.get_about() {
        out.push_str(&format!("{}\n\n", sentence(&about.to_string())));
    }
    let args: Vec<&Arg> = cmd
        .get_arguments()
        .filter(|a| !a.is_hide_set() && !a.is_global_set())
        .filter(|a| !matches!(a.get_id().as_str(), "help" | "version"))
        .collect();
    let mut usage = path.clone();
    for arg in &args {
        if arg.is_required_set() {
            usage.push(' ');
            usage.push_str(&syntax(arg));
        }
    }
    if args.iter().any(|a| !a.is_required_set()) {
        usage.push_str(" [OPTIONS]");
    }
    out.push_str(&format!("```sh\n{usage}\n```\n"));
    if args.is_empty() {
        return;
    }
    out.push_str("\n| Argument | Required | Description |\n|---|---|---|\n");
    for arg in args {
        let mut help = sentence(&arg.get_help().map(|h| h.to_string()).unwrap_or_default());
        let defaults: Vec<String> = arg
            .get_default_values()
            .iter()
            .map(|v| v.to_string_lossy().into_owned())
            .filter(|v| !v.is_empty())
            .collect();
        if !defaults.is_empty() {
            help = format!("{help} Default: `{}`.", defaults.join(", "))
                .trim()
                .to_owned();
        }
        out.push_str(&format!(
            "| `{}` | {} | {} |\n",
            syntax(arg),
            if arg.is_required_set() { "Yes" } else { "No" },
            cell(&help)
        ));
    }
}

fn syntax(arg: &Arg) -> String {
    let value = arg
        .get_value_names()
        .and_then(|names| names.first().map(|n| n.to_string()))
        .unwrap_or_else(|| arg.get_id().as_str().to_uppercase());
    match arg.get_long() {
        Some(long) if matches!(arg.get_action(), ArgAction::SetTrue) => format!("--{long}"),
        Some(long) => format!("--{long} <{value}>"),
        None => format!("<{value}>"),
    }
}

/// Clap drops the final period of a doc comment; put it back for prose.
fn sentence(text: &str) -> String {
    let text = text.trim();
    if text.is_empty() || text.ends_with(['.', '?', '!', ')']) {
        text.to_owned()
    } else {
        format!("{text}.")
    }
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

pub struct ToolDoc {
    pub name: &'static str,
    pub description: &'static str,
    pub changes: bool,
    pub schema: Value,
}

pub fn mcp(tools: Vec<ToolDoc>, prompt: &str) -> String {
    let mut out = String::from(
        "---\ntitle: MCP tool reference\ndescription: The tools and prompt that visiconvert mcp offers AI agents.\n---\n\n\
         {/* Generated by `visiconvert reference mcp`. Do not edit by hand. */}\n\n\
         **Read** tools are always available. **Change** tools are listed only when the server \
         is started with `visiconvert mcp --allow-changes`. No tool accepts Twilio credentials.\n",
    );
    for tool in tools {
        let tier = if tool.changes { "Change" } else { "Read" };
        out.push_str(&format!(
            "\n## `{}`\n\n**{tier}.** {}\n",
            tool.name, tool.description
        ));
        let required: Vec<&str> = tool.schema["required"]
            .as_array()
            .map(|r| r.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let Some(properties) = tool.schema["properties"].as_object() else {
            continue;
        };
        if properties.is_empty() {
            out.push_str("\nNo arguments.\n");
            continue;
        }
        out.push_str("\n| Argument | Type | Required | Description |\n|---|---|---|---|\n");
        for (name, property) in properties {
            let mut kind = property["type"].as_str().unwrap_or("any").to_owned();
            if let Some(values) = property["enum"].as_array() {
                let values: Vec<String> = values
                    .iter()
                    .filter_map(Value::as_str)
                    .map(|v| format!("`{v}`"))
                    .collect();
                kind = values.join(", ");
            }
            let mut description = sentence(property["description"].as_str().unwrap_or(""));
            if let Some(default) = property.get("default") {
                description = format!("{description} Default: `{default}`.")
                    .trim()
                    .to_owned();
            }
            out.push_str(&format!(
                "| `{name}` | {kind} | {} | {} |\n",
                if required.contains(&name.as_str()) {
                    "Yes"
                } else {
                    "No"
                },
                cell(&description)
            ));
        }
    }
    out.push_str("\n## Prompt: `set_up_call_tracking`\n\nWalks an agent through setup:\n\n");
    for line in prompt.lines().skip_while(|l| !l.starts_with("1.")) {
        out.push_str(line);
        out.push('\n');
    }
    out
}
