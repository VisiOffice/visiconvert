import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { once } from 'node:events';
import path from 'node:path';
export async function verifyDni({browser,page,origin,api,artifactDir}) {
  await page.setViewportSize({width:1440,height:1000});
  let siteId;
  const fixture=createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end(`<!doctype html><html><head><title>DNI business</title><script defer src="${origin}/tracker.js" data-site="${siteId}" data-dni="true"></script></head><body><h1>Call our business</h1><a id="phone" aria-label="(202) 555-0106" data-visiconvert-phone href="tel:+12025550106">(202) 555-0106</a><span id="text" data-visiconvert-phone>202-555-0106</span><a id="unmarked" href="tel:+12025550106">Normal link</a><a id="other" data-visiconvert-phone href="tel:+12025550109">202-555-0109</a><span id="nested" data-visiconvert-phone><b>202-555-0106</b></span></body></html>`);});
  fixture.listen(0,'127.0.0.1');await once(fixture,'listening');
  const business=`http://127.0.0.1:${fixture.address().port}`;
  const visitor=await browser.newPage(), second=await browser.newPage();
  const errors=[]; visitor.on('pageerror',e=>errors.push(e.message));
  try {
    await page.getByRole('button',{name:'Sites',exact:true}).click();
    await page.getByLabel('Website name',{exact:true}).fill('DNI verification');
    await page.getByLabel('Website origin',{exact:true}).fill(business);
    await page.getByRole('button',{name:'Add website',exact:true}).click();
    await page.getByRole('status').filter({hasText:'Site saved.'}).waitFor();
    siteId=(await api('/sites')).body.sites.find(s=>s.name==='DNI verification').id;
    await page.getByLabel('Business fallback number',{exact:true}).fill('+12025550106');
    await page.getByRole('checkbox',{name:/\+12025550105/}).check();
    await page.getByLabel('Enable number swapping',{exact:true}).check();
    await page.getByLabel('These numbers are used only for this website’s pool.',{exact:true}).check();
    await page.getByRole('button',{name:'Save number pool',exact:true}).click();
    await page.getByRole('status').filter({hasText:'Number pool saved.'}).waitFor();
    await visitor.goto(`${business}/?utm_source=google&utm_campaign=dni-browser`);
    await visitor.waitForFunction(()=>!!window.VisiConvert);
    assert.equal(await visitor.locator('#phone').textContent(),'(202) 555-0106');
    await visitor.evaluate(()=>window.VisiConvert.setConsent(true));
    assert.equal(await visitor.locator('#phone').textContent(),'+12025550105');
    assert.equal(await visitor.locator('#phone').getAttribute('href'),'tel:+12025550105');
    assert.equal(await visitor.locator('#text').textContent(),'+12025550105');
    assert.equal(await visitor.locator('#phone').getAttribute('aria-label'),'+12025550105');
    assert.equal(await visitor.locator('#unmarked').getAttribute('href'),'tel:+12025550106');
    assert.equal(await visitor.locator('#other').getAttribute('href'),'tel:+12025550109');
    assert.equal(await visitor.locator('#nested b').textContent(),'202-555-0106');
    await visitor.evaluate(()=>{const n=document.createElement('a');n.id='dynamic';n.dataset.visiconvertPhone='';n.href='tel:+12025550106';n.textContent='202-555-0106';document.body.append(n);});
    await visitor.waitForFunction(()=>document.querySelector('#dynamic').textContent==='+12025550105');
    await second.goto(business);await second.waitForFunction(()=>!!window.VisiConvert);await second.evaluate(()=>window.VisiConvert.setConsent(true));
    assert.equal(await second.locator('#phone').getAttribute('href'),'tel:+12025550106','Exhausted pool uses normal business line');
    // Explicit network fault injection: last number must not remain on failure.
    await visitor.route('**/collect/sites/*/numbers',route=>route.abort());
    assert.equal((await visitor.evaluate(()=>window.VisiConvert.refreshNumbers())).status,'unavailable');
    assert.equal(await visitor.locator('#phone').textContent(),'(202) 555-0106');
    assert.equal(await visitor.locator('#dynamic').getAttribute('href'),'tel:+12025550106');
    await visitor.unroute('**/collect/sites/*/numbers');
    await visitor.evaluate(()=>window.VisiConvert.refreshNumbers());
    assert.equal(await visitor.locator('#phone').textContent(),'+12025550105');
    // Exercise local expiry without waiting half an hour; preserve the real API response.
    await visitor.route('**/collect/sites/*/numbers',async route=>{const response=await route.fetch();const body=await response.json();body.expires_at=new Date(Date.now()+400).toISOString();await route.fulfill({response,json:body});});
    await visitor.evaluate(()=>window.VisiConvert.refreshNumbers());
    await visitor.waitForFunction(()=>document.querySelector('#phone').textContent==='(202) 555-0106');
    await visitor.unroute('**/collect/sites/*/numbers');
    await visitor.evaluate(()=>window.VisiConvert.refreshNumbers());
    await visitor.evaluate(()=>window.VisiConvert.setConsent(false));
    assert.equal(await visitor.locator('#phone').textContent(),'(202) 555-0106');
    assert.equal((await visitor.evaluate(()=>window.VisiConvert.refreshNumbers())).status,'off');
    assert.equal(await visitor.locator('#phone').getAttribute('aria-label'),'(202) 555-0106');
    const data=(await api(`/sites/${siteId}/number-pool`)).body;
    assert.equal(data.history.length,1);assert(data.pool.fallback_count>=1);
    await page.getByRole('button',{name:'Refresh pool',exact:true}).click();
    await page.getByText('Recent number assignments (1)',{exact:true}).click();
    await page.screenshot({path:path.join(artifactDir,'dni-pool-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:path.join(artifactDir,'dni-pool-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.getByLabel('Enable number swapping',{exact:true}).uncheck();
    await page.getByRole('button',{name:'Save number pool',exact:true}).click();
    await page.getByRole('status').filter({hasText:'Number pool saved.'}).waitFor();
    assert.equal((await second.evaluate(()=>window.VisiConvert.refreshNumbers())).status,'disabled');
    assert.deepEqual(errors,[]);
  } finally {await visitor.close();await second.close();await new Promise(resolve=>fixture.close(resolve));}
}
